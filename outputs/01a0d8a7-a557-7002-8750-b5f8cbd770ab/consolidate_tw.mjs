import fs from 'node:fs/promises';
import { FileBlob, Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const dir = 'D:/program/TECHM8 PRICE LIST/outputs/01a0d8a7-a557-7002-8750-b5f8cbd770ab';
const source = await SpreadsheetFile.importXlsx(await FileBlob.load(`${dir}/TW-FF-2026-09-repair-costs-fx47.xlsx`));
const workbook = Workbook.create();
const oldTw = source.worksheets.getItem('TW').getRange('A8:J80').values;
const groups = new Map();
for (const r of oldTw) {
  if (!r[3]) continue;
  const key = JSON.stringify([r[2] || '', r[3], r[5], r[6], r[7]]);
  if (!groups.has(key)) groups.set(key, { device: r[2] || '', item: r[3], cost: r[5], currency: r[6], gst: r[7], qty: 0, sales: 0, tickets: [], notes: [] });
  const g = groups.get(key);
  g.qty += 1;
  g.sales += Number(r[4] || 0);
  if (r[1]) g.tickets.push(String(r[1]));
  if (r[9] && !g.notes.includes(String(r[9]))) g.notes.push(String(r[9]));
}
const sh = workbook.worksheets.add('TW 汇总');
sh.showGridLines = false;
sh.tabColor = '#155E75';
sh.getRange('A1:J1').merge();
sh.getRange('A1').values = [['TW｜2026年9月维修成本（同项目合并）']];
sh.getRange('A1:J1').format = { fill: '#15324A', font: { name: 'Microsoft YaHei', size: 16, bold: true, color: '#FFFFFF' } };
sh.getRange('A1:J1').format.rowHeight = 34;
sh.getRange('A2:J2').merge();
sh.getRange('A2').values = [['同机型、同维修项目、同单次成本与货币的记录合并；不同机型或不同成本保持分行。来源为已填写的逐单表。']];
sh.getRange('A4:B4').values = [['维修销售条目数', oldTw.filter(r => r[3]).length]];
sh.getRange('D4:E4').values = [['合并后项目行数', groups.size]];
sh.getRange('G4:H4').values = [['1 AUD = CNY', 4.7]];
sh.getRange('A6:J6').values = [['设备/机型', '维修项目', '数量', '单次配件成本', '货币', 'GST 口径', '销售额含 GST', '配件总成本 AUD 不含 GST', '工单号', '备注']];
sh.getRange('A6:J6').format = { fill: '#155E75', font: { name: 'Microsoft YaHei', bold: true, color: '#FFFFFF' } };
const data = [...groups.values()].map(g => [g.device, g.item, g.qty, g.cost, g.currency, g.gst, Math.round(g.sales * 100) / 100, null, g.tickets.join(', '), g.notes.join('；')]);
const first = 7, last = first + data.length - 1;
sh.getRange(`A${first}:J${last}`).values = data;
sh.getRange(`H${first}`).formulas = [[`=IF(OR(D${first}="",NOT(ISNUMBER(D${first}))),"",IF(E${first}="CNY",C${first}*D${first}/$H$4,IF(F${first}="含 GST",C${first}*D${first}/1.1,IF(F${first}="不含 GST",C${first}*D${first},""))))`]];
sh.getRange(`H${first}:H${last}`).fillDown();
sh.getRange(`D${first}:F${last}`).format.fill = '#FFF1D6';
sh.getRange(`A${first}:J${last}`).format.borders = { preset: 'all', style: 'thin', color: '#D9E2E8' };
sh.getRange(`D${first}:D${last}`).format.numberFormat = '$#,##0.00';
sh.getRange(`G${first}:H${last}`).format.numberFormat = '$#,##0.00';
sh.getRange('A:A').format.columnWidth = 36;
sh.getRange('B:B').format.columnWidth = 76;
sh.getRange('C:C').format.columnWidth = 10;
sh.getRange('D:D').format.columnWidth = 22;
sh.getRange('E:F').format.columnWidth = 15;
sh.getRange('G:H').format.columnWidth = 25;
sh.getRange('I:I').format.columnWidth = 56;
sh.getRange('J:J').format.columnWidth = 46;
sh.freezePanes.freezeRows(6);
const ff = workbook.worksheets.add('FF 逐单');
ff.showGridLines = false;
ff.tabColor = '#9A3412';
const oldFf = source.worksheets.getItem('FF').getRange('A1:J50').values;
ff.getRange('A1:J50').values = oldFf.map(row => row.map(v => typeof v === 'string' && v.startsWith('=') ? null : v));
ff.getRange('A1:J1').format = { fill: '#15324A', font: { name: 'Microsoft YaHei', size: 16, bold: true, color: '#FFFFFF' } };
ff.getRange('A1:J1').format.rowHeight = 34;
ff.getRange('A7:J7').format = { fill: '#155E75', font: { name: 'Microsoft YaHei', bold: true, color: '#FFFFFF' } };
ff.getRange('F8:H50').format.fill = '#FFF1D6';
ff.getRange('H5').format.fill = '#FFF1D6';
ff.getRange('A:A').format.columnWidth = 14;
ff.getRange('B:B').format.columnWidth = 25;
ff.getRange('C:C').format.columnWidth = 40;
ff.getRange('D:D').format.columnWidth = 72;
ff.getRange('E:E').format.columnWidth = 20;
ff.getRange('F:F').format.columnWidth = 20;
ff.getRange('G:H').format.columnWidth = 15;
ff.getRange('I:I').format.columnWidth = 24;
ff.getRange('J:J').format.columnWidth = 45;
ff.getRange('E5').formulas = [['=COUNTBLANK(F8:F50)']];
ff.getRange('I8').formulas = [['=IF(F8="","",IF(G8="CNY",IF($H$5="","",F8*$H$5),IF(H8="含 GST",F8/1.1,IF(H8="不含 GST",F8,""))))']];
ff.getRange('I8:I50').fillDown();
ff.freezePanes.freezeRows(7);
workbook.recalculate();
for (const name of ['TW 汇总', 'FF 逐单']) {
  const preview = await workbook.render({ sheetName: name, range: name === 'TW 汇总' ? 'A1:J12' : 'A1:J12', scale: 1.2, format: 'png' });
  await fs.writeFile(`${dir}/${name === 'TW 汇总' ? 'TW-consolidated' : 'FF-unchanged'}-preview.png`, new Uint8Array(await preview.arrayBuffer()));
}
const file = await SpreadsheetFile.exportXlsx(workbook);
await file.save(`${dir}/TW-consolidated-FF-repair-costs.xlsx`);
console.log(`TW ${data.length} groups from ${oldTw.filter(r => r[3]).length} repair lines; FF ${oldFf.slice(7).filter(r => r[3]).length} lines`);
