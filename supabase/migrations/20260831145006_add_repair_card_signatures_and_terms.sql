-- Digital repair card: replaces the paper intake card the stores sign today.
--
-- A signature is a contract, so nothing about it is editable. Re-signing (a
-- mistyped phone number, a wrong price) inserts a new row and marks the old one
-- superseded; no row is ever updated in place or deleted.
--
-- Each signature freezes the terms text and a snapshot of everything the
-- customer actually saw on screen, so a later change to the ticket or to the
-- terms can never rewrite what was agreed.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('repair-cards', 'repair-cards', false, 5242880, array['image/png','image/jpeg','image/webp'])
on conflict (id) do nothing;

create table if not exists public.pos_repair_card_terms (
  version text primary key,
  body text not null,
  active boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.pos_repair_card_signatures (
  id bigint generated by default as identity primary key,
  signature_code text not null unique,
  repair_ticket_id bigint not null references public.pos_repair_tickets(id) on delete cascade,
  store_id bigint not null references public.store_locations(id) on delete restrict,
  signature_path text not null,
  signed_customer_name text not null,
  terms_version text not null references public.pos_repair_card_terms(version),
  terms_text text not null,
  card_snapshot jsonb not null,
  witnessed_by text not null,
  signed_at timestamptz not null default now(),
  superseded_at timestamptz,
  superseded_reason text,
  superseded_by_signature_code text,
  created_at timestamptz not null default now()
);

create index if not exists pos_repair_card_signatures_ticket_idx
  on public.pos_repair_card_signatures (repair_ticket_id, signed_at desc);

create index if not exists pos_repair_card_signatures_current_idx
  on public.pos_repair_card_signatures (repair_ticket_id)
  where superseded_at is null;

alter table public.pos_repair_card_terms enable row level security;
alter table public.pos_repair_card_signatures enable row level security;
revoke all on public.pos_repair_card_terms from public, anon, authenticated;
revoke all on public.pos_repair_card_signatures from public, anon, authenticated;
grant select on public.pos_repair_card_terms to service_role;
grant select, insert, update on public.pos_repair_card_signatures to service_role;

comment on table public.pos_repair_card_signatures is
  'Immutable signed repair cards. Re-signing inserts a new row and supersedes the previous one; rows are never edited or deleted.';
comment on column public.pos_repair_card_signatures.card_snapshot is
  'Exactly what the customer saw when they signed. Render the card from this, never from the live ticket.';

