-- Monthly sales target per store. Admin sets it on the Sales Overview page; the
-- POS Today card shows it against the store's month-to-date takings, plus the
-- signed-in staff member's points for the month (Google reviews + device and
-- accessory bundles). Takings use the same cash-basis ledger as the admin
-- overview, so "This Month" there and the POS progress always agree.

create table if not exists public.pos_store_sales_targets (
  id bigint generated by default as identity primary key,
  store_id bigint not null references public.store_locations(id) on delete restrict,
  target_month date not null,
  sales_target numeric(12,2) not null check (sales_target > 0 and sales_target <= 99999999),
  updated_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pos_store_sales_targets_first_day_check
    check (target_month = date_trunc('month', target_month)::date),
  constraint pos_store_sales_targets_store_month_unique unique (store_id, target_month)
);

drop trigger if exists pos_store_sales_targets_set_updated_at on public.pos_store_sales_targets;
create trigger pos_store_sales_targets_set_updated_at
before update on public.pos_store_sales_targets
for each row execute function public.set_updated_at();

alter table public.pos_store_sales_targets enable row level security;
revoke all on public.pos_store_sales_targets from public, anon, authenticated;
grant select, insert, update, delete on public.pos_store_sales_targets to service_role;

create or replace function public.pos_store_month_sales_progress(
  target_store_id bigint,
  target_business_date date
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  date_value date := coalesce(target_business_date, (now() at time zone 'Australia/Brisbane')::date);
  month_value date := date_trunc('month', coalesce(target_business_date, (now() at time zone 'Australia/Brisbane')::date))::date;
  month_end_value date;
  days_left_value integer;
  net_sales_value numeric(12,2) := 0;
  target_row public.pos_store_sales_targets%rowtype;
  remaining_value numeric(12,2);
begin
  month_end_value := (month_value + interval '1 month - 1 day')::date;
  days_left_value := greatest(1, month_end_value - date_value + 1);

  select coalesce(sum(movement.amount), 0)
  into net_sales_value
  from public.pos_takings_line_movements(array[target_store_id], month_value, date_value) movement;

  select * into target_row
  from public.pos_store_sales_targets sales_target_row
  where sales_target_row.store_id = target_store_id
    and sales_target_row.target_month = month_value;

  if target_row.id is not null then
    remaining_value := greatest(0, target_row.sales_target - net_sales_value);
  end if;

  return jsonb_build_object(
    'month', to_char(month_value, 'YYYY-MM'),
    'date_from', month_value,
    'date_to', date_value,
    'days_in_month', extract(day from month_end_value)::integer,
    'days_left', days_left_value,
    'net_sales', net_sales_value,
    'target', target_row.sales_target,
    'remaining', remaining_value,
    'percent', case when target_row.id is not null
      then round(net_sales_value / target_row.sales_target * 100, 1) end,
    'daily_needed', case when target_row.id is not null
      then round(remaining_value / days_left_value, 2) end,
    'updated_by', target_row.updated_by,
    'updated_at', target_row.updated_at
  );
end;
$$;

-- Same rules as the admin staff points report: reviews and paid device +
-- accessory invoices across every store this month.
create or replace function public.pos_staff_month_points(
  target_staff_name text,
  target_business_date date
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  staff_key text := lower(trim(coalesce(target_staff_name, '')));
  date_value date := coalesce(target_business_date, (now() at time zone 'Australia/Brisbane')::date);
  month_value date := date_trunc('month', coalesce(target_business_date, (now() at time zone 'Australia/Brisbane')::date))::date;
  review_count_value integer := 0;
  review_points_value integer := 0;
  bundle_order_value integer := 0;
  device_value integer := 0;
  accessory_value integer := 0;
  bundle_points_value integer := 0;
begin
  if staff_key = '' then raise exception 'Staff member is required'; end if;

  select count(*)::integer, coalesce(sum(review_event.points), 0)::integer
  into review_count_value, review_points_value
  from public.pos_google_review_events review_event
  where review_event.normalized_staff_name = staff_key
    and review_event.business_date between month_value and date_value;

  select
    coalesce(sum(bundle.bundle_order_count), 0)::integer,
    coalesce(sum(bundle.device_count), 0)::integer,
    coalesce(sum(bundle.accessory_count), 0)::integer,
    coalesce(sum(bundle.bundle_points), 0)::integer
  into bundle_order_value, device_value, accessory_value, bundle_points_value
  from public.store_locations store_location
  cross join lateral public.pos_bundle_score_metrics(store_location.id, month_value, date_value, staff_key) bundle;

  return jsonb_build_object(
    'month', to_char(month_value, 'YYYY-MM'),
    'date_from', month_value,
    'date_to', date_value,
    'google_review_count', review_count_value,
    'google_review_points', review_points_value,
    'bundle_order_count', bundle_order_value,
    'bundle_device_count', device_value,
    'bundle_accessory_count', accessory_value,
    'bundle_points', bundle_points_value,
    'total_points', review_points_value + bundle_points_value
  );
end;
$$;

-- Month figures stay live even after the day's score is finalized.
