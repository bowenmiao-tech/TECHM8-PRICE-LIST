create or replace function public.get_pos_today_progress(
  session_token text,
  target_store_code text,
  target_staff_name text,
  target_business_date date default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected_store public.store_locations%rowtype;
  staff_value text := trim(coalesce(target_staff_name, ''));
  date_value date := coalesce(target_business_date, (now() at time zone 'Australia/Brisbane')::date);
  finalized_result public.pos_daily_target_results%rowtype;
  has_open_shift boolean := false;
  progress_payload jsonb;
  month_figures jsonb;
begin
  if not public.is_valid_staff_session(session_token) then raise exception 'Invalid session'; end if;
  if staff_value = '' then raise exception 'Staff member is required'; end if;

  select * into selected_store
  from public.store_locations store_location
  where store_location.active = true
    and store_location.store_code = coalesce(trim(target_store_code), '')
    and store_location.store_code <> 'warehouse';
  if not found then raise exception 'Store not found'; end if;

  month_figures := public.pos_today_progress_month_figures(selected_store.id, staff_value, date_value);

  select exists (
    select 1
    from public.pos_store_shifts shift_record
    where shift_record.store_id = selected_store.id
      and shift_record.business_date = date_value
      and shift_record.status = 'open'
  ) into has_open_shift;

  if not has_open_shift then
    select * into finalized_result
    from public.pos_daily_target_results result
    where result.store_id = selected_store.id
      and result.business_date = date_value
      and result.normalized_staff_name = lower(staff_value)
    order by result.finalized_at desc
    limit 1;

    if found then
      return finalized_result.progress_payload || jsonb_build_object(
        'status', 'finalized',
        'finalized_at', finalized_result.finalized_at,
        'finalized_by', finalized_result.finalized_by,
        'shift_code', finalized_result.shift_code
      ) || month_figures;
    end if;
  end if;

  progress_payload := public.pos_today_progress_payload(selected_store.id, date_value, staff_value);
  return progress_payload || jsonb_build_object('status', 'projected') || month_figures;
end;
$$;

-- The review response replaces the POS card, so it carries the month figures
-- too (the new review is already in the month total).
create or replace function public.record_pos_google_review(
  session_token text,
  target_store_code text,
  target_staff_name text,
  event_code text,
  customer_name text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected_store public.store_locations%rowtype;
  selected_staff public.staff_directory%rowtype;
  date_value date := (now() at time zone 'Australia/Brisbane')::date;
  event_code_value text := trim(coalesce(event_code, ''));
  customer_value text := trim(coalesce(record_pos_google_review.customer_name, ''));
begin
  if not public.is_valid_staff_session(session_token) then raise exception 'Invalid session'; end if;
  if event_code_value = '' then raise exception 'Review event id is required'; end if;
  if customer_value = '' then raise exception 'Customer name is required for a Google review'; end if;
  if length(customer_value) > 120 then raise exception 'Customer name is too long'; end if;

  select * into selected_store
  from public.store_locations store_location
  where store_location.active = true
    and store_location.store_code = coalesce(trim(target_store_code), '')
    and store_location.store_code <> 'warehouse';
  if not found then raise exception 'Store not found'; end if;

  select * into selected_staff
  from public.staff_directory staff
  where staff.active = true
    and lower(trim(staff.display_name)) = lower(trim(coalesce(target_staff_name, '')))
  limit 1;
  if not found then raise exception 'Staff member not found'; end if;

  if not exists (
    select 1 from public.pos_store_shifts shift_record
    where shift_record.store_id = selected_store.id
      and shift_record.business_date = date_value
      and shift_record.status = 'open'
  ) then
    raise exception 'Google reviews can only be recorded during an open shift';
  end if;

  if exists (
    select 1 from public.pos_daily_target_results result
    where result.store_id = selected_store.id
      and result.business_date = date_value
      and result.normalized_staff_name = lower(trim(selected_staff.display_name))
  ) then
    raise exception 'Today score has already been finalized';
  end if;

  insert into public.pos_google_review_events (
    event_code, store_id, business_date, staff_name, points, customer_name
  ) values (
    event_code_value, selected_store.id, date_value, selected_staff.display_name, 5, customer_value
  )
  on conflict on constraint pos_google_review_events_event_code_key do nothing;

  return public.pos_today_progress_payload(selected_store.id, date_value, selected_staff.display_name)
    || public.pos_today_progress_month_figures(selected_store.id, selected_staff.display_name, date_value);
end;
$$;

create or replace function public.get_admin_store_sales_targets(
  session_token text,
  target_month_start date default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  today_value date := (now() at time zone 'Australia/Brisbane')::date;
  month_value date := date_trunc('month', coalesce(target_month_start, (now() at time zone 'Australia/Brisbane')::date))::date;
  month_end_value date;
  sales_to_value date;
  result_payload jsonb;
begin
  if not public.is_valid_admin_session(session_token) then raise exception 'Invalid admin session'; end if;
  month_end_value := (month_value + interval '1 month - 1 day')::date;
  sales_to_value := least(month_end_value, today_value);

  with selected_stores as materialized (
    select
      store_location.id,
      store_location.store_code,
      store_location.store_name,
      coalesce(array_position(array['parkridge','fairfield','northlakes','toowong','brassall']::text[], store_location.store_code), 99) as display_order
    from public.store_locations store_location
    where store_location.active
      and store_location.store_code <> 'warehouse'
  ),
  -- A future month has no takings yet; the ledger returns nothing when
  -- the start date is after the end date.
  store_sales as (
    select movement.store_id, coalesce(sum(movement.amount), 0)::numeric(12,2) as net_sales
    from public.pos_takings_line_movements(array(select selected_store.id from selected_stores selected_store), month_value, sales_to_value) movement
    group by movement.store_id
  )
  select jsonb_build_object(
    'ok', true,
    'month', to_char(month_value, 'YYYY-MM'),
    'month_start', month_value,
    'month_end', month_end_value,
    'sales_to', case when sales_to_value >= month_value then sales_to_value end,
    'days_in_month', extract(day from month_end_value)::integer,
    'days_elapsed', greatest(0, sales_to_value - month_value + 1),
    'stores', coalesce(jsonb_agg(jsonb_build_object(
      'store_code', selected_store.store_code,
      'store_name', selected_store.store_name,
      'sales_target', sales_target_row.sales_target,
      'net_sales', coalesce(store_sale.net_sales, 0),
      'updated_by', sales_target_row.updated_by,
      'updated_at', sales_target_row.updated_at
    ) order by selected_store.display_order, selected_store.store_name), '[]'::jsonb)
  )
  into result_payload
  from selected_stores selected_store
  left join store_sales store_sale on store_sale.store_id = selected_store.id
  left join public.pos_store_sales_targets sales_target_row
    on sales_target_row.store_id = selected_store.id
   and sales_target_row.target_month = month_value;

  return result_payload;
end;
$$;

-- An empty or zero amount removes the store's target for that month.
create or replace function public.set_admin_store_sales_target(
  session_token text,
  target_store_code text,
  target_month_start date,
  target_amount numeric
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected_store public.store_locations%rowtype;
  month_value date;
  amount_value numeric(12,2) := round(target_amount, 2);
  actor_value text;
begin
  if not public.is_valid_admin_session(session_token) then raise exception 'Invalid admin session'; end if;
  if target_month_start is null then raise exception 'Month is required'; end if;
  if amount_value < 0 then raise exception 'Target cannot be negative'; end if;
  if amount_value > 99999999 then raise exception 'Target is too large'; end if;
  month_value := date_trunc('month', target_month_start)::date;

  select * into selected_store
  from public.store_locations store_location
  where store_location.active = true
    and store_location.store_code = coalesce(trim(target_store_code), '')
    and store_location.store_code <> 'warehouse';
  if not found then raise exception 'Store not found'; end if;

  actor_value := coalesce(nullif(trim(public.admin_session_actor_name(session_token)), ''), 'Admin portal');

  if coalesce(amount_value, 0) = 0 then
    delete from public.pos_store_sales_targets sales_target_row
    where sales_target_row.store_id = selected_store.id
      and sales_target_row.target_month = month_value;
  else
    insert into public.pos_store_sales_targets (store_id, target_month, sales_target, updated_by)
    values (selected_store.id, month_value, amount_value, actor_value)
    on conflict on constraint pos_store_sales_targets_store_month_unique
    do update set sales_target = excluded.sales_target, updated_by = excluded.updated_by;
  end if;

  return public.get_admin_store_sales_targets(session_token, month_value);
end;
$$;

