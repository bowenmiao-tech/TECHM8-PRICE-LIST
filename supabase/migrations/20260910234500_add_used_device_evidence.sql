-- Photographic evidence and a running memo for second-hand devices.
--
-- The buyback register was text-only: `photo_urls` existed on the device row
-- but nothing ever wrote to it, and the single `notes` field was overwritten by
-- every save. This adds the same append-only comment/photo store the repair
-- board already uses, with a stage on each entry so intake evidence, seller ID,
-- refurbishment work and listing photos stay separable.
--
-- Intake photos are taken before the money moves. The POS uploads them against
-- a client-generated `intake_key` while the purchase form is still open, and
-- the acquisition claims them in the same transaction that pays the seller, so
-- a purchase without evidence cannot be saved at all.
--
-- Seller ID images are deliberately kept in their own bucket, are readable only
-- through an admin session, and every read is logged.

create table public.pos_used_device_updates (
  id uuid primary key,
  device_id bigint not null references public.pos_used_devices(id) on delete restrict,
  kind text not null check (kind in ('comment', 'photo')),
  stage text not null check (stage in ('intake', 'seller_id', 'refurb', 'listing')),
  body text not null default '' check (length(body) <= 5000),
  storage_path text unique,
  file_name text,
  author text not null,
  created_at timestamptz not null default now(),
  check ((kind = 'comment' and length(btrim(body)) > 0 and storage_path is null)
    or (kind = 'photo' and storage_path is not null))
);

create index pos_used_device_updates_device_date_idx
  on public.pos_used_device_updates (device_id, created_at desc);

create index pos_used_device_updates_stage_idx
  on public.pos_used_device_updates (device_id, stage)
  where kind = 'photo';

-- Evidence photographed before the device record exists. A row is claimed by
-- the acquisition that consumes it and is never reused.
create table public.pos_used_device_intake_uploads (
  id uuid primary key,
  store_id bigint not null references public.store_locations(id) on delete restrict,
  intake_key uuid not null,
  stage text not null check (stage in ('intake', 'seller_id')),
  storage_path text not null unique,
  file_name text,
  author text not null,
  created_at timestamptz not null default now(),
  claimed_device_id bigint references public.pos_used_devices(id) on delete restrict
);

create index pos_used_device_intake_uploads_open_idx
  on public.pos_used_device_intake_uploads (intake_key)
  where claimed_device_id is null;

-- Who looked at a seller's identity document, and when.
create table public.pos_used_device_id_photo_views (
  id bigint generated by default as identity primary key,
  update_id uuid not null references public.pos_used_device_updates(id) on delete restrict,
  viewer text not null,
  viewed_at timestamptz not null default now()
);

create index pos_used_device_id_photo_views_update_idx
  on public.pos_used_device_id_photo_views (update_id, viewed_at desc);

alter table public.pos_used_device_updates enable row level security;
alter table public.pos_used_device_intake_uploads enable row level security;
alter table public.pos_used_device_id_photo_views enable row level security;

revoke all on public.pos_used_device_updates from public, anon, authenticated;
revoke all on public.pos_used_device_intake_uploads from public, anon, authenticated;
revoke all on public.pos_used_device_id_photo_views from public, anon, authenticated;

grant all on public.pos_used_device_updates to service_role;
grant all on public.pos_used_device_intake_uploads to service_role;
grant all on public.pos_used_device_id_photo_views to service_role;

