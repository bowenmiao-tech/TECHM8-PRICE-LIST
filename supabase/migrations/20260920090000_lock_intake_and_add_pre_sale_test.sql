-- 5. The shop floor can no longer rewrite the purchase inspection, and
--    "ready for sale" now means "passed its pre-sale test".
do $migration$
declare
  definition text;
  patched text;
  previous text;
begin
  select replace(pg_get_functiondef(oid), chr(13), '') into definition
  from pg_proc
  where proname = 'update_pos_used_device' and pronamespace = 'public'::regnamespace;
  if definition is null then raise exception 'update_pos_used_device was not found'; end if;

  patched := definition;

  previous := patched;
  patched := replace(
    patched,
    $anchor$  inspection_value := case
    when jsonb_typeof(payload->'inspection') = 'object' then payload->'inspection'
    else device_row.inspection
  end;$anchor$,
    $replacement$  -- The purchase inspection is locked; a caller cannot replace it here.
  inspection_value := device_row.inspection;$replacement$
  );
  if patched = previous then
    raise exception 'pre-sale test patch: the inspection assignment anchor was not found';
  end if;

  previous := patched;
  patched := replace(
    patched,
    $anchor$    or not public.pos_used_device_inspection_complete(device_row.category, inspection_value)$anchor$,
    $replacement$    or not public.pos_used_device_sale_test_passed(device_row.id)$replacement$
  );
  if patched = previous then
    raise exception 'pre-sale test patch: the ready gate anchor was not found';
  end if;

  previous := patched;
  patched := replace(
    patched,
    $anchor$'Device cannot be marked ready until all checks pass'$anchor$,
    $replacement$'Device cannot be marked ready until it passes a pre-sale test and the lock, data and stolen checks are done'$replacement$
  );
  if patched = previous then
    raise exception 'pre-sale test patch: the ready message anchor was not found';
  end if;

  execute patched;
end;
$migration$;

-- 6. What stands between a device and the website, reading the pre-sale test.
create or replace function public.pos_used_device_listing_blockers(target_device_id bigint)
returns text[]
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  device_row public.pos_used_devices%rowtype;
  blockers text[] := array[]::text[];
  latest_answers jsonb;
  outstanding integer;
begin
  select * into device_row from public.pos_used_devices where id = target_device_id;
  if not found then return array['This device no longer exists']; end if;
  if device_row.status = 'sold' then return array['This device has been sold']; end if;
  if device_row.status in ('returned_to_seller', 'disposed') then
    return array['This device is closed and no longer in stock'];
  end if;

  if not exists (select 1 from public.pos_used_device_sale_tests test where test.device_id = device_row.id) then
    blockers := array_append(blockers, 'No pre-sale test has been recorded yet');
  else
    latest_answers := public.pos_used_device_latest_sale_test_answers(device_row.id);
    select count(*) into outstanding
    from public.pos_used_device_inspection_items item
    where item.active
      and item.category = device_row.category
      and lower(coalesce(latest_answers->>item.item_key, '')) not in ('pass', 'na');
    if outstanding > 0 then
      blockers := array_append(blockers, format('The latest pre-sale test has %s check%s not passed', outstanding,
        case when outstanding = 1 then '' else 's' end));
    end if;
  end if;

  if device_row.clean_check_status not in ('Clean', 'Not Applicable') then
    blockers := array_append(blockers, format('The lost or stolen check is still %s', lower(device_row.clean_check_status)));
  end if;
  if not device_row.activation_lock_removed then
    blockers := array_append(blockers, 'Activation locks are not confirmed removed');
  end if;
  if not device_row.data_erased_confirmed then
    blockers := array_append(blockers, 'Customer data is not confirmed erased');
  end if;
  if device_row.evidence_required and not exists (
    select 1 from public.pos_used_device_updates entry
    where entry.device_id = device_row.id and entry.kind = 'photo' and entry.stage = 'listing'
  ) then
    blockers := array_append(blockers, 'No listing photo has been added');
  end if;

  return blockers;
end;
$$;

