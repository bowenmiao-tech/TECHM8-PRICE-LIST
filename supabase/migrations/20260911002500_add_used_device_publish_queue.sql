-- The public description, built from the inspection record.
--
-- This function decides what the world sees, so it reads only the fields that
-- are safe to show. It never touches the IMEI, the serial number, the seller,
-- the purchase price, or the internal memo.
create or replace function public.pos_used_device_listing_payload(target_device_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  device_row public.pos_used_devices%rowtype;
  store_row public.store_locations%rowtype;
  checklist_total integer;
  checklist_passed integer;
  highlights jsonb := '[]'::jsonb;
  condition_line text;
  closing_line text;
  description_text text;
  title_text text;
  images_payload jsonb;
begin
  select * into device_row from public.pos_used_devices where id = target_device_id;
  if not found then raise exception 'Used device not found'; end if;
  select * into store_row from public.store_locations where id = device_row.store_id;

  select count(*) into checklist_total
  from public.pos_used_device_inspection_items item
  where item.active and item.category = device_row.category;

  select count(*) into checklist_passed
  from public.pos_used_device_inspection_items item
  where item.active and item.category = device_row.category
    and lower(coalesce(device_row.inspection->>item.item_key, '')) = 'pass';

  select coalesce(value, 'Tested in store before sale.') into condition_line
  from public.pos_used_device_listing_copy where key = 'condition.' || device_row.condition_grade;
  select coalesce(value, '') into closing_line
  from public.pos_used_device_listing_copy where key = 'closing';

  if checklist_total > 0 then
    highlights := highlights || to_jsonb(format('%s of %s inspection checks passed', checklist_passed, checklist_total));
  end if;
  if device_row.battery_health is not null then
    highlights := highlights || to_jsonb(format('Battery health %s%%', device_row.battery_health));
  end if;
  if device_row.storage <> '' then
    highlights := highlights || to_jsonb(device_row.storage || ' storage');
  end if;
  if device_row.data_erased_confirmed then
    highlights := highlights || to_jsonb('Wiped and reset, ready to set up'::text);
  end if;
  if device_row.activation_lock_removed then
    highlights := highlights || to_jsonb('No previous owner account attached'::text);
  end if;
  if store_row.store_name is not null then
    highlights := highlights || to_jsonb('In stock at ' || store_row.store_name);
  end if;

  title_text := btrim(regexp_replace(
    concat_ws(' ', device_row.brand, device_row.model, nullif(device_row.storage, ''), nullif(device_row.color, '')),
    '\s+', ' ', 'g'));

  description_text := btrim(concat_ws(E'\n\n', condition_line, nullif(closing_line, '')));

  -- Numbered in a subquery: a window function cannot live inside the aggregate
  -- that collects it.
  select coalesce(jsonb_agg(jsonb_build_object(
    'storage_path', ordered.storage_path,
    'position', ordered.position
  ) order by ordered.position), '[]'::jsonb) into images_payload
  from (
    select entry.storage_path,
           row_number() over (order by entry.created_at, entry.id) as position
    from public.pos_used_device_updates entry
    where entry.device_id = device_row.id and entry.kind = 'photo' and entry.stage = 'listing'
  ) ordered;

  return jsonb_build_object(
    'device_code', device_row.device_code,
    'device_category', device_row.category,
    'store_code', coalesce(store_row.store_code, ''),
    'title', title_text,
    'brand', device_row.brand,
    'model', device_row.model,
    'storage', device_row.storage,
    'color', device_row.color,
    'condition_grade', device_row.condition_grade,
    'condition_summary', condition_line,
    'battery_health', device_row.battery_health,
    'price', device_row.sale_price,
    'description', description_text,
    'highlights', highlights,
    'images', images_payload,
    'website_status', device_row.website_status,
    'website_slug', device_row.website_slug
  );
end;
$$;

-- Queues the intention only. Marking the device `queued` is the caller's job,
-- so the trigger below can do it on the row it is already writing instead of
-- updating the same row from inside its own trigger.
create or replace function public.enqueue_pos_used_device_publish(
  target_device_id bigint,
  target_device_code text,
  target_action text,
  actor_name text default 'system'
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  version_value bigint := nextval('public.pos_used_device_publish_version_seq');
  queue_id bigint;
begin
  if target_action not in ('publish', 'withdraw', 'sold') then raise exception 'Invalid publish action'; end if;

  -- One pending intention per device. A newer one replaces whatever was
  -- waiting, so a device that goes ready then sold in a minute publishes once.
  insert into public.pos_used_device_publish_queue (device_id, device_code, action, source_version, requested_by)
  values (target_device_id, target_device_code, target_action, version_value, coalesce(nullif(actor_name, ''), 'system'))
  on conflict (device_id) where completed_at is null
  do update set
    action = excluded.action,
    source_version = excluded.source_version,
    requested_by = excluded.requested_by,
    requested_at = now(),
    claimed_at = null,
    attempts = 0,
    last_error = ''
  returning id into queue_id;

  return queue_id;
end;
$$;

-- Status and price changes drive the website by themselves. Staff do not have
-- to remember to take a sold device down.
create or replace function public.queue_pos_used_device_website_sync()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  action_value text;
begin
  if new.status = 'sold' and old.status <> 'sold' then
    action_value := 'sold';
  elsif new.status = 'ready_for_sale'
    and (old.status <> 'ready_for_sale' or new.sale_price is distinct from old.sale_price) then
    -- Newly on the shelf, or a change the public page needs to show.
    action_value := 'publish';
  elsif old.status = 'ready_for_sale' and new.status <> 'ready_for_sale' then
    action_value := 'withdraw';
  else
    return new;
  end if;

  perform public.enqueue_pos_used_device_publish(new.id, new.device_code, action_value, new.updated_by);
  new.website_status := 'queued';
  return new;
end;
$$;

drop trigger if exists pos_used_devices_queue_website_sync on public.pos_used_devices;
create trigger pos_used_devices_queue_website_sync
before update of status, sale_price on public.pos_used_devices
for each row execute function public.queue_pos_used_device_website_sync();

-- The worker's two calls: take work, then say what happened.
create or replace function public.claim_pos_used_device_publish_batch(batch_limit integer default 10)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  safe_limit integer := least(greatest(coalesce(batch_limit, 10), 1), 50);
  result jsonb;
begin
  with claimed as (
    update public.pos_used_device_publish_queue queue
    set claimed_at = now(), attempts = queue.attempts + 1
    where queue.id in (
      select inner_queue.id
      from public.pos_used_device_publish_queue inner_queue
      where inner_queue.completed_at is null
        and inner_queue.attempts < 5
        and (inner_queue.claimed_at is null or inner_queue.claimed_at < now() - interval '5 minutes')
      order by inner_queue.requested_at
      limit safe_limit
      for update skip locked
    )
    returning queue.*
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'queue_id', claimed.id,
    'action', claimed.action,
    'source_version', claimed.source_version,
    'attempts', claimed.attempts,
    'listing', public.pos_used_device_listing_payload(claimed.device_id)
  ) order by claimed.requested_at), '[]'::jsonb) into result
  from claimed;

  return jsonb_build_object('ok', true, 'items', result);
end;
$$;

create or replace function public.complete_pos_used_device_publish(payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  queue_id bigint := nullif(payload->>'queue_id', '')::bigint;
  succeeded boolean := lower(coalesce(payload->>'ok', 'false')) = 'true';
  slug_value text := trim(coalesce(payload->>'slug', ''));
  error_value text := left(trim(coalesce(payload->>'error', '')), 500);
  queue_row public.pos_used_device_publish_queue%rowtype;
begin
  select * into queue_row from public.pos_used_device_publish_queue where id = queue_id for update;
  if not found then raise exception 'Publish request not found'; end if;
  if queue_row.completed_at is not null then
    return jsonb_build_object('ok', true, 'already_completed', true);
  end if;

  if succeeded then
    update public.pos_used_device_publish_queue
    set completed_at = now(), last_error = ''
    where id = queue_row.id;

    update public.pos_used_devices
    set website_status = case queue_row.action when 'publish' then 'published' else 'withdrawn' end,
        website_slug = case when slug_value <> '' then slug_value else website_slug end,
        website_synced_at = now()
    where id = queue_row.device_id;
    return jsonb_build_object('ok', true, 'completed', true);
  end if;

  update public.pos_used_device_publish_queue
  set last_error = error_value, claimed_at = null
  where id = queue_row.id;

  -- Five tries is enough to distinguish a blip from a broken listing.
  if queue_row.attempts >= 5 then
    update public.pos_used_devices set website_status = 'failed' where id = queue_row.device_id;
  end if;
  return jsonb_build_object('ok', true, 'completed', false, 'attempts', queue_row.attempts);
end;
$$;

-- The POS button: publish or take down this one device now.
create or replace function public.request_pos_used_device_publish(session_token text, payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  context jsonb;
  device_row public.pos_used_devices%rowtype;
  action_value text := coalesce(nullif(trim(payload->>'action'), ''), 'publish');
begin
  context := public.authorize_pos_used_device_evidence(
    session_token, payload->>'store_code', payload->>'device_code');
  select * into device_row from public.pos_used_devices where id = (context->>'device_id')::bigint;

  if action_value not in ('publish', 'withdraw') then raise exception 'Invalid publish action'; end if;
  if action_value = 'publish' then
    if device_row.status <> 'ready_for_sale' then
      raise exception 'Only a device that is ready for sale can go on the website';
    end if;
    if not exists (
      select 1 from public.pos_used_device_updates entry
      where entry.device_id = device_row.id and entry.kind = 'photo' and entry.stage = 'listing'
    ) then
      raise exception 'Add at least one listing photo before publishing';
    end if;
  end if;

  perform public.enqueue_pos_used_device_publish(
    device_row.id, device_row.device_code, action_value, context->>'author');
  update public.pos_used_devices set website_status = 'queued' where id = device_row.id;
  return jsonb_build_object('ok', true, 'device_code', device_row.device_code, 'website_status', 'queued');
end;
$$;

-- What the POS shows against a device: where it stands on the website, and the
-- reason if the last attempt did not get there.
create or replace function public.get_pos_used_device_website_status(session_token text, store_code text, device_code text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  context jsonb;
  device_row public.pos_used_devices%rowtype;
  queue_row public.pos_used_device_publish_queue%rowtype;
begin
  context := public.authorize_pos_used_device_evidence(session_token, store_code, device_code);
  select * into device_row from public.pos_used_devices where id = (context->>'device_id')::bigint;
  select * into queue_row from public.pos_used_device_publish_queue
  where device_id = device_row.id and completed_at is null
  order by requested_at desc limit 1;

  return jsonb_build_object(
    'ok', true,
    'website_status', device_row.website_status,
    'website_slug', device_row.website_slug,
    'website_synced_at', device_row.website_synced_at,
    'listing_photo_count', (
      select count(*) from public.pos_used_device_updates entry
      where entry.device_id = device_row.id and entry.kind = 'photo' and entry.stage = 'listing'
    ),
    'can_publish', device_row.status = 'ready_for_sale',
    'pending', case when queue_row.id is null then null else jsonb_build_object(
      'action', queue_row.action,
      'requested_at', queue_row.requested_at,
      'attempts', queue_row.attempts,
      'last_error', queue_row.last_error
    ) end
  );
end;
$$;

