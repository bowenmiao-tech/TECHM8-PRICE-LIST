-- Publishing a device to the public website.
--
-- The website catalogue lives in a different Supabase project, so there is no
-- transaction that can span the two. Writing straight across would mean a
-- half-published device whenever the network blinked. Instead the POS records
-- an intention -- publish, withdraw, sold -- and a worker carries it over and
-- reports back. A device that fails to publish stays queued and visibly failed
-- rather than silently disagreeing with the shop floor.
--
-- Only one intention per device is ever pending: a later one replaces the
-- earlier one, and `source_version` from a sequence lets the website reject a
-- slow retry that would otherwise undo a newer state.

create sequence public.pos_used_device_publish_version_seq;

alter table public.pos_used_devices
  add column website_status text not null default 'not_published'
    check (website_status in ('not_published', 'queued', 'published', 'withdrawn', 'failed')),
  add column website_slug text not null default '',
  add column website_synced_at timestamptz;

create table public.pos_used_device_publish_queue (
  id bigint generated by default as identity primary key,
  device_id bigint not null references public.pos_used_devices(id) on delete restrict,
  device_code text not null,
  action text not null check (action in ('publish', 'withdraw', 'sold')),
  source_version bigint not null,
  requested_by text not null default 'system',
  requested_at timestamptz not null default now(),
  claimed_at timestamptz,
  attempts integer not null default 0,
  last_error text not null default '',
  completed_at timestamptz
);

create unique index pos_used_device_publish_queue_pending_idx
  on public.pos_used_device_publish_queue (device_id)
  where completed_at is null;

create index pos_used_device_publish_queue_ready_idx
  on public.pos_used_device_publish_queue (requested_at)
  where completed_at is null;

alter table public.pos_used_device_publish_queue enable row level security;
revoke all on public.pos_used_device_publish_queue from public, anon, authenticated;
grant all on public.pos_used_device_publish_queue to service_role;

