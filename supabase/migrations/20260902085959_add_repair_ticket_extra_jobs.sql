-- A repair card can now carry more than one job. An inspection that turns into
-- a battery replacement, or a battery job where the screen turns out to be
-- cracked, stays on the same card instead of needing a second ticket.
--
-- Existing tickets are deliberately left untouched: the ticket's own
-- title/price remains job #1, and this table only holds the jobs added
-- afterwards. So a card nobody has extended behaves exactly as it does today
-- and no backfill is needed.

create table if not exists public.pos_repair_ticket_jobs (
  id bigint generated by default as identity primary key,
  job_code text not null unique,
  repair_ticket_id bigint not null references public.pos_repair_tickets(id) on delete cascade,
  name text not null,
  price numeric(12,2) not null,
  note text not null default '',
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_by text not null default '',
  updated_at timestamptz not null default now(),
  constraint pos_repair_ticket_jobs_price_check check (price > 0 and price <= 1000000),
  constraint pos_repair_ticket_jobs_name_check check (btrim(name) <> '')
);

create index if not exists pos_repair_ticket_jobs_ticket_idx
  on public.pos_repair_ticket_jobs (repair_ticket_id, created_at);

-- Ties an invoice line back to the exact job it billed. A repair line with a
-- null job id is the ticket's original job, which is how every line written
-- before this change is read.
alter table public.pos_sales_order_lines
  add column if not exists repair_job_id bigint
  references public.pos_repair_ticket_jobs(id) on delete restrict;

create index if not exists pos_sales_order_lines_repair_job_idx
  on public.pos_sales_order_lines (repair_job_id)
  where repair_job_id is not null;

-- The previous workflow allowed exactly one repair line per ticket. Multi-job
-- cards need one base line plus one line for each extra job instead. Keep both
-- kinds unique independently so concurrent checkouts cannot bill either twice.
drop index if exists public.pos_sales_order_lines_repair_ticket_unique;
create unique index if not exists pos_sales_order_lines_repair_ticket_base_unique
  on public.pos_sales_order_lines (repair_ticket_id)
  where repair_ticket_id is not null and repair_job_id is null;
drop index if exists public.pos_sales_order_lines_repair_job_idx;
create unique index pos_sales_order_lines_repair_job_idx
  on public.pos_sales_order_lines (repair_job_id)
  where repair_job_id is not null;

alter table public.pos_repair_ticket_jobs enable row level security;
revoke all on public.pos_repair_ticket_jobs from public, anon, authenticated;
grant select, insert, update, delete on public.pos_repair_ticket_jobs to service_role;

comment on table public.pos_repair_ticket_jobs is
  'Extra repairs added to a card after intake. The card''s own issue/price is job #1 and is not stored here.';
comment on column public.pos_sales_order_lines.repair_job_id is
  'Which extra job this line billed. Null on a repair line means the ticket''s original job.';
