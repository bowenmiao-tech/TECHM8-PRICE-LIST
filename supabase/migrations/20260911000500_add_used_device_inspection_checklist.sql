-- Every active item for this category, answered pass or N/A. Anything else --
-- a fail, a blank, or a missing key -- keeps the device off the shelf.
create or replace function public.pos_used_device_inspection_complete(device_category text, answers jsonb)
returns boolean
language sql
stable
set search_path = ''
as $$
  select not exists (
    select 1
    from public.pos_used_device_inspection_items item
    where item.active
      and item.category = device_category
      and lower(coalesce(answers->>item.item_key, '')) not in ('pass', 'na')
  );
$$;

create or replace function public.get_pos_used_device_inspection_items(session_token text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  if not public.is_valid_staff_session(session_token) then raise exception 'Invalid session'; end if;
  select coalesce(jsonb_object_agg(category, items), '{}'::jsonb) into result
  from (
    select item.category,
      jsonb_agg(jsonb_build_object('key', item.item_key, 'label', item.label) order by item.position, item.id) as items
    from public.pos_used_device_inspection_items item
    where item.active
    group by item.category
  ) grouped;
  return jsonb_build_object('ok', true, 'checklists', result);
end;
$$;

revoke all on function public.pos_used_device_inspection_complete(text, jsonb) from public, anon, authenticated;
revoke all on function public.get_pos_used_device_inspection_items(text) from public, anon, authenticated;
grant execute on function public.pos_used_device_inspection_complete(text, jsonb) to service_role;
grant execute on function public.get_pos_used_device_inspection_items(text) to anon, authenticated, service_role;

-- Replace the count-based gate in update_pos_used_device with the checklist.
do $migration$
declare
  definition text;
  patched text;
begin
  select pg_get_functiondef(oid) into definition
  from pg_proc
  where proname = 'update_pos_used_device' and pronamespace = 'public'::regnamespace;
  if definition is null then raise exception 'update_pos_used_device was not found'; end if;

  patched := replace(
    definition,
    $anchor$    or (select count(*) from jsonb_each_text(inspection_value) result where lower(result.value) in ('pass', 'na')) < 8
    or exists (select 1 from jsonb_each_text(inspection_value) result where lower(result.value) not in ('pass', 'na'))$anchor$,
    $replacement$    or not public.pos_used_device_inspection_complete(device_row.category, inspection_value)$replacement$
  );
  if patched = definition then
    raise exception 'inspection checklist patch: the answer-count anchor was not found';
  end if;
  execute patched;
end;
$migration$;

