-- The inspection checklist becomes shared data instead of a number.
--
-- The ready-for-sale gate counted answers: at least eight of them had to say
-- pass or N/A. A phone checklist has twenty-three items, so a caller that
-- skipped the POS could shelf a phone after answering eight. The checklist now
-- lives in the database, one row per item per category, and every item for the
-- device's category must be answered before it can be sold.
--
-- The POS reads the same rows, so the paper form, the screen and the gate
-- cannot drift apart. The lists here are the ones the POS was already drawing,
-- taken from TECHM8_Buyback_Device_Inspection_Form.pdf.

create table public.pos_used_device_inspection_items (
  id bigint generated by default as identity primary key,
  category text not null check (category in ('Phone', 'Tablet', 'Laptop', 'Watch', 'Game Console', 'Other')),
  item_key text not null,
  label text not null,
  position integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (category, item_key)
);

create index pos_used_device_inspection_items_category_idx
  on public.pos_used_device_inspection_items (category, position)
  where active;

alter table public.pos_used_device_inspection_items enable row level security;
revoke all on public.pos_used_device_inspection_items from public, anon, authenticated;
grant select on public.pos_used_device_inspection_items to service_role;

