-- A balance payment on an older invoice may not yet have an account code.
-- Bind it to the verified customer before the payment trigger spends credit.
create or replace function public.add_pos_sales_order_payment_for_store(
  session_token text,
  payload jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  shift_context jsonb;
  selected_order public.pos_sales_orders%rowtype;
  sanitized_payload jsonb;
  order_code_value text := coalesce(trim(payload->>'order_id'), trim(payload->>'id'), '');
  credit_customer_code text := coalesce(trim(payload->>'customer_code'), '');
begin
  if jsonb_typeof(payload) <> 'object' then raise exception 'Payment payload must be an object'; end if;
  shift_context := public.pos_open_shift_context(
    session_token, payload->>'store_code', payload->>'shift_id', payload->>'staff_name', true
  );
  select * into selected_order
  from public.pos_sales_orders sales_order
  where sales_order.order_code = order_code_value
    and sales_order.store_id = nullif(shift_context->>'store_id', '')::bigint
  for update;
  if not found then raise exception 'Invoice not found in the current store'; end if;

  if exists (
    select 1 from jsonb_array_elements(coalesce(payload->'payments', '[]'::jsonb)) payment
    where lower(trim(payment->>'method')) = 'store credit'
  ) then
    perform public.pos_store_credit_customer_for_order(selected_order, credit_customer_code);
    if nullif(selected_order.order_payload->>'customer_code', '') is not null
      and selected_order.order_payload->>'customer_code' <> credit_customer_code then
      raise exception 'This invoice is already linked to another customer account';
    end if;
    update public.pos_sales_orders
    set order_payload = order_payload || jsonb_build_object('customer_code', credit_customer_code)
    where id = selected_order.id;
  end if;

  sanitized_payload := payload || jsonb_build_object(
    'store_code', shift_context->>'store_code',
    'staff_name', shift_context->>'staff_name',
    'shift_id', shift_context->>'shift_id',
    'business_date', shift_context->>'business_date',
    'taken_at', now()
  );
  return public.add_pos_sales_order_payment(session_token, sanitized_payload);
end;
$$;

-- Keep financial takings separate from the customer's credit liability.
alter function public.get_pos_shift_payment_totals(text,text)
  rename to get_pos_shift_payment_totals_before_store_credit;
create function public.get_pos_shift_payment_totals(session_token text, target_shift_code text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  result_payload jsonb;
  credit_received numeric(12,2);
begin
  result_payload := public.get_pos_shift_payment_totals_before_store_credit(session_token, target_shift_code);
  select coalesce(sum((entry->>'received')::numeric), 0) into credit_received
  from jsonb_array_elements(result_payload->'payment_totals') entry
  where lower(trim(entry->>'method')) = 'store credit';
  return jsonb_set(
    jsonb_set(result_payload, '{payment_totals}', coalesce((
      select jsonb_agg(entry) from jsonb_array_elements(result_payload->'payment_totals') entry
      where lower(trim(entry->>'method')) <> 'store credit'
    ), '[]'::jsonb)),
    '{gross_sales}', to_jsonb((result_payload->>'gross_sales')::numeric - credit_received)
  );
end;
$$;
revoke all on function public.get_pos_shift_payment_totals(text,text) from public,anon,authenticated;
grant execute on function public.get_pos_shift_payment_totals(text,text) to service_role;

alter function public.get_pos_performance_report(text,text,date,date,integer)
  rename to get_pos_performance_report_before_store_credit;
create function public.get_pos_performance_report(
  session_token text, target_store_code text, date_from date default null,
  date_to date default null, order_limit integer default 300
)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  result_payload jsonb;
  credit_issued numeric(12,2);
  credit_redeemed numeric(12,2);
  totals jsonb;
begin
  result_payload := public.get_pos_performance_report_before_store_credit(
    session_token, target_store_code, date_from, date_to, order_limit
  );
  select
    coalesce(sum((entry->>'received')::numeric), 0),
    coalesce(sum((entry->>'refunded')::numeric), 0)
  into credit_redeemed, credit_issued
  from jsonb_array_elements(result_payload->'payment_totals') entry
  where lower(trim(entry->>'method')) = 'store credit';
  totals := result_payload->'totals';
  totals := totals || jsonb_build_object(
    'received', (totals->>'received')::numeric - credit_redeemed,
    'refunded', (totals->>'refunded')::numeric - credit_issued,
    'net', (totals->>'net')::numeric - credit_redeemed + credit_issued,
    'store_credit_issued', credit_issued,
    'store_credit_redeemed', credit_redeemed
  );
  return jsonb_set(result_payload, '{totals}', totals);
end;
$$;
revoke all on function public.get_pos_performance_report(text,text,date,date,integer)
  from public,anon,authenticated;
grant execute on function public.get_pos_performance_report(text,text,date,date,integer) to service_role;

alter function public.get_admin_sales_overview(text,date,date)
  rename to get_admin_sales_overview_before_store_credit;
create function public.get_admin_sales_overview(
  session_token text, date_from date default null, date_to date default null
)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  result_payload jsonb;
  store_row jsonb;
  adjusted_stores jsonb := '[]'::jsonb;
  credit_by_store numeric(12,2);
  total_credit numeric(12,2) := 0;
  from_value date := coalesce(date_from, (now() at time zone 'Australia/Brisbane')::date);
  to_value date := coalesce(date_to, date_from, (now() at time zone 'Australia/Brisbane')::date);
begin
  result_payload := public.get_admin_sales_overview_before_store_credit(session_token, date_from, date_to);
  for store_row in select value from jsonb_array_elements(result_payload->'stores') loop
    select coalesce(sum(payment.amount), 0) into credit_by_store
    from public.pos_sales_order_payments payment
    join public.pos_sales_orders sales_order on sales_order.id = payment.sales_order_id
    join public.store_locations store on store.id = sales_order.store_id
    where store.store_code = store_row->>'store_code'
      and lower(trim(payment.method)) = 'store credit'
      and coalesce(payment.business_date, (payment.created_at at time zone 'Australia/Brisbane')::date)
          between from_value and to_value;
    total_credit := total_credit + credit_by_store;
    adjusted_stores := adjusted_stores || jsonb_build_array(
      jsonb_set(store_row, '{payments_received}',
        to_jsonb((store_row->>'payments_received')::numeric - credit_by_store))
    );
  end loop;
  result_payload := jsonb_set(result_payload, '{stores}', adjusted_stores);
  return jsonb_set(result_payload, '{totals,payments_received}',
    to_jsonb((result_payload #>> '{totals,payments_received}')::numeric - total_credit));
end;
$$;
revoke all on function public.get_admin_sales_overview(text,date,date) from public,anon,authenticated;
grant execute on function public.get_admin_sales_overview(text,date,date) to anon,authenticated,service_role;
