-- Inter-store used-device transfer, and a network view of every store's stock.
--
-- Two things staff could not do before this:
--
--   1. Move a second-hand device to another store. Stock Transfer only moves
--      counted product lines (model + variant + quantity). A used device is a
--      single serialised item with its own history, so it could not ride on a
--      quantity line, and there was no other route. Devices moved physically
--      and the register silently went stale.
--   2. See what the other stores are holding. Every used-device read was
--      hard-scoped to one store, so a customer asking "do you have a 13 Pro
--      Max?" could only be answered for the store standing in front of them.
--
-- HOW THE TRANSFER IS MADE TRUSTWORTHY
--
-- Ownership moves on RECEIPT, never on dispatch. Between the two the device is
-- in transit: the sending store can no longer sell it, publish it or send it
-- again, and the receiving store does not own it yet. Nothing is ever in two
-- places, and nothing is in no place.
--
-- Each transfer freezes a `device_snapshot` at dispatch: what was handed over,
-- by IMEI, condition, battery and price, as it read at that moment. Editing the
-- device afterwards cannot rewrite what the transfer says was sent. If a phone
-- arrives in worse condition than it left, the snapshot is the evidence.
--
-- Both ends write to pos_used_device_transactions, the same ledger the buyback
-- and the sale write to, so one device's whole life reads in one place:
-- transfer_out at the sender, transfer_in at the receiver, transfer_cancelled
-- if it is recalled.
--
-- Only the sending store can send or cancel; only the receiving store can
-- receive. That is enforced in the database, not in the page, so it holds no
-- matter who calls it.
--
-- WHAT THE NETWORK VIEW DELIBERATELY DOES NOT SHOW
--
-- Staff at Toowong can see Park Ridge's devices, their prices, their condition
-- and their store notes -- including devices still on the bench, because the
-- question "is one in the group anywhere" has to be answerable before it is
-- tested. They cannot see who sold it, that person's phone, address or ID, or
-- what the store paid. Seller identity is another store's customer's private
-- data, and purchase cost is already hidden from staff by
-- 20260912030000_hide_used_device_cost_from_staff. Widening the view must not
-- quietly widen either of those.

-- ---------------------------------------------------------------------------
-- 1. The ledger learns the three transfer events.
-- ---------------------------------------------------------------------------
alter table public.pos_used_device_transactions
  drop constraint if exists pos_used_device_transactions_transaction_type_check;

alter table public.pos_used_device_transactions
  add constraint pos_used_device_transactions_transaction_type_check
  check (transaction_type in (
    'acquisition', 'status_change', 'price_change', 'sale', 'refund_return',
    'returned_to_seller', 'disposal', 'detail_change',
    'transfer_out', 'transfer_in', 'transfer_cancelled'
  ));

-- ---------------------------------------------------------------------------
-- 2. The transfer record.
-- ---------------------------------------------------------------------------
create table if not exists public.pos_used_device_transfers (
  id bigint generated by default as identity primary key,
  transfer_code text not null unique,
  device_id bigint not null references public.pos_used_devices(id) on delete restrict,
  from_store_id bigint not null references public.store_locations(id) on delete restrict,
  to_store_id bigint not null references public.store_locations(id) on delete restrict,
  status text not null check (status in ('in_transit', 'received', 'cancelled')),
  -- What was actually handed over, frozen at dispatch. A later edit to the
  -- device cannot change this.
  device_snapshot jsonb not null,
  sent_by text not null,
  sent_at timestamptz not null default now(),
  sent_note text not null default '',
  received_by text,
  received_at timestamptz,
  received_note text not null default '',
  receipt_photo_url text not null default '',
  cancelled_by text,
  cancelled_at timestamptz,
  cancel_reason text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pos_used_device_transfers_distinct_stores check (from_store_id <> to_store_id)
);

-- A device can only be on one journey at a time. This is what stops a device
-- being sent to two stores at once.
create unique index if not exists pos_used_device_transfers_one_active_idx
on public.pos_used_device_transfers (device_id)
where status = 'in_transit';

create index if not exists pos_used_device_transfers_to_store_idx
on public.pos_used_device_transfers (to_store_id, status, sent_at desc);

create index if not exists pos_used_device_transfers_from_store_idx
on public.pos_used_device_transfers (from_store_id, status, sent_at desc);

create index if not exists pos_used_device_transfers_device_idx
on public.pos_used_device_transfers (device_id, sent_at desc);

comment on table public.pos_used_device_transfers is
  'Store-to-store movement of a single second-hand device. Ownership changes on receipt, not dispatch; device_snapshot freezes what was sent.';

