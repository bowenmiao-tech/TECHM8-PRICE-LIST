  left join lateral (
    select transfer.*
    from public.pos_used_device_transfers transfer
    where transfer.device_id = device_row.id and transfer.status = 'in_transit'
    limit 1
  ) active_transfer on true
  left join public.store_locations from_store on from_store.id = active_transfer.from_store_id
  left join public.store_locations to_store on to_store.id = active_transfer.to_store_id
  where store_location.id = device_row.store_id;
