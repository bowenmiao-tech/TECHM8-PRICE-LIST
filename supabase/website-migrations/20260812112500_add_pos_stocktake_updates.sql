create table if not exists public.pos_stocktake_changes (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete restrict,
  product_group_id bigint references public.product_groups(id) on delete set null,
  store_id bigint not null references public.stores(id) on delete restrict,
  staff_name text not null,
  old_pos_category_id bigint references public.pos_category_taxonomy(id) on delete set null,
  new_pos_category_id bigint not null references public.pos_category_taxonomy(id) on delete restrict,
  old_quantity integer not null,
  new_quantity integer not null,
  created_at timestamptz not null default now()
);

create index if not exists pos_stocktake_changes_store_created_idx
  on public.pos_stocktake_changes (store_id, created_at desc);
create index if not exists pos_stocktake_changes_product_created_idx
  on public.pos_stocktake_changes (product_id, created_at desc);

