create or replace function public.apply_pos_stocktake_update(
  target_product_id bigint,
  target_store_slug text,
  target_pos_category_id bigint,
  target_quantity integer,
  target_staff_name text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_product public.products%rowtype;
  selected_group public.product_groups%rowtype;
  selected_store public.stores%rowtype;
  selected_taxonomy public.pos_category_taxonomy%rowtype;
  previous_category_id bigint;
  previous_quantity integer := 0;
begin
  if target_quantity is null or target_quantity < 0 or target_quantity > 1000000 then
    raise exception 'Stock quantity must be between 0 and 1000000';
  end if;

  if coalesce(trim(target_staff_name), '') = '' then
    raise exception 'Staff name is required';
  end if;

  select *
  into selected_product
  from public.products
  where id = target_product_id
    and is_pos_visible = true
  for update;

  if selected_product.id is null then
    raise exception 'POS product not found';
  end if;

  select *
  into selected_store
  from public.stores
  where slug = trim(target_store_slug)
    and is_active = true;

  if selected_store.id is null then
    raise exception 'Active store not found';
  end if;

  select *
  into selected_taxonomy
  from public.pos_category_taxonomy
  where id = target_pos_category_id
    and active = true;

  if selected_taxonomy.id is null then
    raise exception 'Active POS category not found';
  end if;

  if selected_product.product_group_id is not null then
    select *
    into selected_group
    from public.product_groups
    where id = selected_product.product_group_id
    for update;

    previous_category_id := selected_group.pos_category_id;

    update public.product_groups
    set
      pos_category_id = selected_taxonomy.id,
      updated_at = now()
    where id = selected_group.id;
  else
    previous_category_id := selected_product.pos_category_id;

    update public.products
    set
      pos_category_id = selected_taxonomy.id,
      updated_at = now()
    where id = selected_product.id;
  end if;

  select coalesce(inventory.quantity, 0)
  into previous_quantity
  from public.product_store_inventory inventory
  where inventory.product_id = selected_product.id
    and inventory.store_id = selected_store.id
  for update;

  previous_quantity := coalesce(previous_quantity, 0);

  insert into public.product_store_inventory (product_id, store_id, quantity, updated_at)
  values (selected_product.id, selected_store.id, target_quantity, now())
  on conflict (product_id, store_id) do update
  set
    quantity = excluded.quantity,
    updated_at = now();

  update public.products
  set
    stock_quantity = (
      select coalesce(sum(inventory.quantity), 0)::integer
      from public.product_store_inventory inventory
      where inventory.product_id = selected_product.id
    ),
    updated_at = now()
  where id = selected_product.id;

  insert into public.pos_stocktake_changes (
    product_id,
    product_group_id,
    store_id,
    staff_name,
    old_pos_category_id,
    new_pos_category_id,
    old_quantity,
    new_quantity
  )
  values (
    selected_product.id,
    selected_product.product_group_id,
    selected_store.id,
    trim(target_staff_name),
    previous_category_id,
    selected_taxonomy.id,
    previous_quantity,
    target_quantity
  );

  return jsonb_build_object(
    'ok', true,
    'product_id', selected_product.id,
    'product_group_id', selected_product.product_group_id,
    'store_slug', selected_store.slug,
    'store_name', selected_store.name,
    'quantity', target_quantity,
    'total_stock', (
      select products.stock_quantity
      from public.products
      where products.id = selected_product.id
    ),
    'previous_quantity', previous_quantity,
    'pos_category_id', selected_taxonomy.id,
    'category', selected_taxonomy.category_name,
    'subcategory', selected_taxonomy.subcategory_name
  );
end;
$$;

revoke all on function public.apply_pos_stocktake_update(bigint, text, bigint, integer, text) from public, anon, authenticated;
grant execute on function public.apply_pos_stocktake_update(bigint, text, bigint, integer, text) to service_role;
