begin;

create table if not exists public.product_fit_profiles (
  id bigint generated by default as identity primary key,
  code text not null unique,
  display_name text not null,
  source_category text not null default '',
  notes text not null default '',
  review_status text not null default 'required'
    check (review_status in ('required', 'proposed', 'approved', 'rejected')),
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now())
);

create table if not exists public.device_models (
  id bigint generated by default as identity primary key,
  code text not null unique,
  brand text not null,
  display_name text not null,
  model_family text not null default '',
  generation text not null default '',
  release_year integer,
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now()),
  constraint device_models_release_year_check
    check (release_year is null or release_year between 2000 and 2100)
);

create table if not exists public.product_fit_profile_devices (
  fit_profile_id bigint not null references public.product_fit_profiles(id) on delete cascade,
  device_model_id bigint not null references public.device_models(id) on delete restrict,
  created_at timestamptz not null default timezone('utc'::text, now()),
  primary key (fit_profile_id, device_model_id)
);

create table if not exists public.product_groups (
  id bigint generated by default as identity primary key,
  code text not null unique,
  slug text not null unique,
  name text not null,
  category_id bigint references public.categories(id) on delete set null,
  product_family text not null,
  fit_profile_id bigint references public.product_fit_profiles(id) on delete restrict,
  main_image_url text,
  status text not null default 'draft'
    check (status in ('draft', 'active', 'archived')),
  is_pos_visible boolean not null default false,
  is_visible boolean not null default false,
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now())
);

alter table public.products
  add column if not exists product_group_id bigint references public.product_groups(id) on delete set null,
  add column if not exists variant_name text,
  add column if not exists variant_color text,
  add column if not exists source_system text,
  add column if not exists source_external_id text,
  add column if not exists source_category_path text,
  add column if not exists import_status text not null default 'active'
    check (import_status in ('draft', 'review', 'active', 'blocked', 'archived')),
  add column if not exists source_metadata jsonb not null default '{}'::jsonb;

create unique index if not exists products_source_identity_unique
on public.products (source_system, source_external_id)
where source_system is not null and source_external_id is not null;

create index if not exists products_product_group_idx
on public.products (product_group_id);

create index if not exists product_groups_category_visibility_idx
on public.product_groups (category_id, is_pos_visible, is_visible, status);

create index if not exists product_groups_fit_profile_idx
on public.product_groups (fit_profile_id);

drop trigger if exists product_fit_profiles_set_updated_at on public.product_fit_profiles;
create trigger product_fit_profiles_set_updated_at
before update on public.product_fit_profiles
for each row execute function public.set_updated_at();

drop trigger if exists device_models_set_updated_at on public.device_models;
create trigger device_models_set_updated_at
before update on public.device_models
for each row execute function public.set_updated_at();

drop trigger if exists product_groups_set_updated_at on public.product_groups;
create trigger product_groups_set_updated_at
before update on public.product_groups
for each row execute function public.set_updated_at();

alter table public.product_fit_profiles enable row level security;
alter table public.device_models enable row level security;
alter table public.product_fit_profile_devices enable row level security;
alter table public.product_groups enable row level security;

revoke all on public.product_fit_profiles from public, anon, authenticated;
revoke all on public.device_models from public, anon, authenticated;
revoke all on public.product_fit_profile_devices from public, anon, authenticated;
revoke all on public.product_groups from public, anon, authenticated;

grant select on public.product_fit_profiles to anon, authenticated;
grant select on public.device_models to anon, authenticated;
grant select on public.product_fit_profile_devices to anon, authenticated;
grant select on public.product_groups to anon, authenticated;

drop policy if exists "public can read visible product groups" on public.product_groups;
create policy "public can read visible product groups"
on public.product_groups for select to anon, authenticated
using (status = 'active' and is_visible = true);

drop policy if exists "public can read approved fit profiles" on public.product_fit_profiles;
create policy "public can read approved fit profiles"
on public.product_fit_profiles for select to anon, authenticated
using (
  review_status = 'approved'
  and exists (
    select 1
    from public.product_groups pg
    where pg.fit_profile_id = product_fit_profiles.id
      and pg.status = 'active'
      and pg.is_visible = true
  )
);

drop policy if exists "public can read compatible device models" on public.device_models;
create policy "public can read compatible device models"
on public.device_models for select to anon, authenticated
using (
  exists (
    select 1
    from public.product_fit_profile_devices pfd
    join public.product_fit_profiles pfp on pfp.id = pfd.fit_profile_id
    join public.product_groups pg on pg.fit_profile_id = pfp.id
    where pfd.device_model_id = device_models.id
      and pfp.review_status = 'approved'
      and pg.status = 'active'
      and pg.is_visible = true
  )
);

drop policy if exists "public can read visible compatibility mappings" on public.product_fit_profile_devices;
create policy "public can read visible compatibility mappings"
on public.product_fit_profile_devices for select to anon, authenticated
using (
  exists (
    select 1
    from public.product_fit_profiles pfp
    join public.product_groups pg on pg.fit_profile_id = pfp.id
    where pfp.id = product_fit_profile_devices.fit_profile_id
      and pfp.review_status = 'approved'
      and pg.status = 'active'
      and pg.is_visible = true
  )
);

insert into public.categories (slug, name, description, sort_order)
values (
  'ipad-tablet-cases',
  'iPad & Tablet Cases',
  'iPad, Samsung tablet, and universal tablet cases.',
  340
)
on conflict (slug) do update
set name = excluded.name,
    description = excluded.description,
    sort_order = excluded.sort_order,
    updated_at = timezone('utc'::text, now());

comment on table public.product_groups is
  'Customer/POS-facing catalog cards. Sellable colors remain separate rows in products.';
comment on table public.product_fit_profiles is
  'Directional case-fit profiles. Compatibility is profile to device only; reverse fit must never be inferred.';
comment on table public.product_fit_profile_devices is
  'Approved directional mappings from a case fit profile to supported device models.';
comment on column public.products.source_external_id is
  'Stable source item identifier used for idempotent imports.';

commit;
