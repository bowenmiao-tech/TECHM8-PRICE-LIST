create or replace function public.register_pos_stock_transfer_photo(
  target_transfer_id bigint,
  target_receipt_key uuid,
  target_category text,
  target_storage_path text,
  target_mime_type text,
  target_file_size integer,
  target_actor_staff_name text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected_transfer public.stock_transfers%rowtype;
  existing_receipt public.stock_transfer_receipts%rowtype;
  saved_photo public.stock_transfer_photos%rowtype;
begin
  if target_receipt_key is null then
    raise exception 'Receipt key is required';
  end if;
  if coalesce(btrim(target_actor_staff_name), '') = '' then
    raise exception 'Staff name is required';
  end if;
  if target_category not in ('receipt', 'issue', 'return') then
    raise exception 'Photo category is invalid';
  end if;
  if target_mime_type not in ('image/jpeg', 'image/png', 'image/webp')
    or target_file_size is null
    or target_file_size < 1
    or target_file_size > 5242880 then
    raise exception 'Photo must be JPEG, PNG or WebP and no larger than 5 MB';
  end if;
  if coalesce(target_storage_path, '') not like
    target_transfer_id::text || '/' || target_receipt_key::text || '/%' then
    raise exception 'Photo storage path does not match the transfer receipt';
  end if;

  select transfer.*
  into selected_transfer
  from public.stock_transfers transfer
  where transfer.id = target_transfer_id;

  if selected_transfer.id is null then
    raise exception 'Transfer not found';
  end if;

  select receipt.*
  into existing_receipt
  from public.stock_transfer_receipts receipt
  where receipt.receipt_key = target_receipt_key;

  if existing_receipt.id is not null and existing_receipt.transfer_id <> selected_transfer.id then
    raise exception 'Receipt key belongs to another transfer';
  end if;
  if existing_receipt.id is null
    and selected_transfer.status not in ('in_transit', 'partially_received') then
    raise exception 'Transfer is no longer available for new receipt photos';
  end if;
  if exists (
    select 1
    from public.stock_transfer_photos photo
    where photo.receipt_key = target_receipt_key
      and photo.transfer_id <> selected_transfer.id
  ) then
    raise exception 'Receipt key belongs to another transfer';
  end if;

  insert into public.stock_transfer_photos (
    transfer_id,
    receipt_key,
    receipt_id,
    category,
    storage_path,
    mime_type,
    file_size,
    uploaded_by
  )
  values (
    selected_transfer.id,
    target_receipt_key,
    existing_receipt.id,
    target_category,
    target_storage_path,
    target_mime_type,
    target_file_size,
    btrim(target_actor_staff_name)
  )
  returning * into saved_photo;

  return jsonb_build_object(
    'id', saved_photo.id,
    'transfer_id', saved_photo.transfer_id,
    'receipt_key', saved_photo.receipt_key,
    'category', saved_photo.category,
    'storage_path', saved_photo.storage_path,
    'mime_type', saved_photo.mime_type,
    'file_size', saved_photo.file_size,
    'uploaded_by', saved_photo.uploaded_by,
    'created_at', saved_photo.created_at
  );
end;
$$;

