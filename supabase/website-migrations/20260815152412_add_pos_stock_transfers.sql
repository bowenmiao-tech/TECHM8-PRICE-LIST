create sequence if not exists public.stock_transfer_number_seq;

create table if not exists public.stock_transfers (
  id bigint generated by default as identity primary key,
  transfer_number text not null unique default (
    'TRF-' || to_char(timezone('Australia/Brisbane', now()), 'YYYYMMDD') || '-'
    || lpad(nextval('public.stock_transfer_number_seq')::text, 6, '0')
  ),
  client_request_key uuid not null unique,
  request_fingerprint text not null,
  source_store_id bigint not null references public.stores(id) on delete restrict,
  destination_store_id bigint not null references public.stores(id) on delete restrict,
  status text not null default 'in_transit'
    check (status in ('in_transit', 'partially_received', 'completed', 'completed_with_issues', 'returned')),
  dispatched_by text not null,
  dispatch_note text,
  dispatched_at timestamptz not null default now(),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  check (source_store_id <> destination_store_id)
);

create table if not exists public.stock_transfer_items (
  id bigint generated by default as identity primary key,
  transfer_id bigint not null references public.stock_transfers(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete restrict,
  sku_snapshot text not null,
  name_snapshot text not null,
  barcode_snapshot text,
  variant_snapshot text,
  dispatched_quantity integer not null check (dispatched_quantity > 0),
  received_good_quantity integer not null default 0 check (received_good_quantity >= 0),
  received_damaged_quantity integer not null default 0 check (received_damaged_quantity >= 0),
  missing_quantity integer not null default 0 check (missing_quantity >= 0),
  returned_quantity integer not null default 0 check (returned_quantity >= 0),
  source_quantity_before integer not null check (source_quantity_before >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (transfer_id, product_id),
  check (
    received_good_quantity + received_damaged_quantity + missing_quantity + returned_quantity
    <= dispatched_quantity
  )
);

create table if not exists public.stock_transfer_receipts (
  id bigint generated by default as identity primary key,
  transfer_id bigint not null references public.stock_transfers(id) on delete cascade,
  receipt_key uuid not null unique,
  request_fingerprint text not null,
  receipt_type text not null check (receipt_type in ('receive', 'return')),
  received_by text not null,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.stock_transfer_receipt_items (
  id bigint generated by default as identity primary key,
  receipt_id bigint not null references public.stock_transfer_receipts(id) on delete cascade,
  transfer_item_id bigint not null references public.stock_transfer_items(id) on delete restrict,
  good_quantity integer not null default 0 check (good_quantity >= 0),
  damaged_quantity integer not null default 0 check (damaged_quantity >= 0),
  missing_quantity integer not null default 0 check (missing_quantity >= 0),
  returned_quantity integer not null default 0 check (returned_quantity >= 0),
  created_at timestamptz not null default now(),
  unique (receipt_id, transfer_item_id),
  check (good_quantity + damaged_quantity + missing_quantity + returned_quantity > 0)
);

create table if not exists public.stock_transfer_photos (
  id uuid primary key default gen_random_uuid(),
  transfer_id bigint not null references public.stock_transfers(id) on delete cascade,
  receipt_key uuid not null,
  receipt_id bigint references public.stock_transfer_receipts(id) on delete set null,
  category text not null default 'receipt' check (category in ('receipt', 'issue', 'return')),
  storage_path text not null unique,
  mime_type text not null check (mime_type in ('image/jpeg', 'image/png', 'image/webp')),
  file_size integer not null check (file_size > 0 and file_size <= 5242880),
  uploaded_by text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  movement_key text not null unique,
  movement_type text not null check (movement_type in ('transfer_out', 'transfer_in', 'transfer_return')),
