import assert from 'node:assert/strict';
import { ipadCategory, protectedIpad, ipadKey, ipadPlan, ipadLabour } from './crazyparts-ipad-rules.mjs';
for(const name of ['iPad Pro 9.7 (2016)','iPad Pro 10.5 (2017)','iPad Air 1','iPad Air 5 (2022)','iPad Mini 3 (2014)']) assert.equal(protectedIpad(name),true);
assert.equal(protectedIpad('iPad Air 11 (2025)'),false);
assert.equal(ipadKey('iPad mini 6 (2021)'),ipadKey('iPad Mini 6 (2022)'));
assert.equal(ipadCategory('REFURB LCD Screen Replacement for iPad Pro 12.9'), 'screen');
assert.equal(ipadCategory('Touch Panel for iPad Pro 12.9 (BQ7)'),null);
assert.equal(ipadCategory('BQ7 Touch Panel with OCA for iPad Pro'),null);
assert.equal(ipadCategory('Greencell Replacement Battery with Adhesive Strips'),'battery');
assert.equal(ipadCategory('Battery FPC Connector for iPad'),null);
assert.equal(ipadCategory('Charging Port with Flex Cable for iPad'),'ipad_port_flat');
assert.equal(ipadCategory('No Solder Charging Port for iPad'),'ipad_port_flat');
assert.equal(ipadCategory('Pencil Charge Port for iPad'),null);
assert.equal(ipadLabour('Charging Port'),179);
assert.equal(ipadLabour('Charging Port (Soldering)'),179);
const rows=[{brand:'Apple iPad',model:'iPad Mini 6 (2022)',issue:'Battery',price:'999'},{brand:'Apple iPad',model:'iPad Air 5 (2022)',issue:'Battery',price:'123'}];
const plan=ipadPlan({repairRows:[{family:'iPad Mini',model:'iPad mini 6 (2021)',repairType:'Battery',minPartPrice:10,maxPartPrice:20},{family:'iPad Air',model:'iPad Air 5 (2022)',repairType:'Battery',minPartPrice:1,maxPartPrice:1}]},rows);
assert.equal(plan.updates.length,1);
assert.equal(plan.updates[0].model,'iPad Mini 6 (2022)');
assert.equal(plan.updates[0].issue,'Battery');
assert.equal(plan.updates[0].newPrice,'165 - 175');
const portPlan=ipadPlan({repairRows:[{family:'iPad Mini',model:'iPad mini 6 (2021)',repairType:'Charging Port',minPartPrice:4.4,maxPartPrice:15.9}]},rows);
assert.equal(portPlan.updates[0].newPrice,'185 - 200');
console.log('PASS: protected models, assembly-only screens, real batteries, uncertain ports, and existing model reuse.');
